  private void tablafacturasMouseClicked(java.awt.event.MouseEvent evt) {
    
    int fila = tablafacturas.getSelectedRow();
    
    if (fila >= 0) {
       
        cmbPedido.setSelectedItem(tablafacturas.getValueAt(fila, 1).toString());
        
       
        jftfFecha.setText(tablafacturas.getValueAt(fila, 2).toString());
        
        txtTotal.setText(tablafacturas.getValueAt(fila, 3).toString());
        
       
        cmbMetodoPago.setSelectedItem(tablafacturas.getValueAt(fila, 4).toString());
    }
}
