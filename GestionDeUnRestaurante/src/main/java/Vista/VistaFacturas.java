    private void cmbPedidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbPedidoActionPerformed
      if (cmbPedido.getSelectedIndex() == -1) {
        txtTotal.setText("");
        return;
    }
    
    try {
        String item = cmbPedido.getSelectedItem().toString();
        int idPedido = Integer.parseInt(item.split(" - ")[0]);
        
        DetallePedidoDAO detalleDAO = new DetallePedidoDAO();
        
        
        List<DetallePedido> lista = detalleDAO.listarPorPedido(idPedido);
        double total = 0;
        
        for (DetallePedido d : lista) {
            total += d.getSubTotal();
        }
        
        txtTotal.setText(String.format("%.2f", total));
        
       
        System.out.println("Pedido ID: " + idPedido + " | Detalles: " + lista.size() + " | Total: " + total);
        
    } catch (Exception e) {
        txtTotal.setText("0.00");
        e.printStackTrace();
    }
    }//GEN-LAST:event_cmbPedidoActionPerformed

    private void btnGenerarFacturaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarFacturaActionPerformed
      if (cmbPedido.getSelectedIndex() == -1) {
        JOptionPane.showMessageDialog(this, "Debes seleccionar un pedido");
        return;
    }
    
    try {
        Factura factura = new Factura();
        
       
        String item = cmbPedido.getSelectedItem().toString();
        int idPedido = Integer.parseInt(item.split(" - ")[0]);
        factura.setIDPedido(idPedido);
        
        
        factura.setFecha(java.time.LocalDateTime.now());
        
        
        String totalTexto = txtTotal.getText().trim().replace(",", ".");
        double total = Double.parseDouble(totalTexto);
        factura.setTotal(total);
        
       
        factura.setMetodoPago(cmbMetodoPago.getSelectedItem().toString());
        
        if (facturaDAO.agregar(factura)) {
            JOptionPane.showMessageDialog(this, "Factura generada correctamente");
            cargarTabla();
            limpiarCampos();
            cargarPedidos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al generar la factura");
        }
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnGenerarFacturaActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tablafacturas.getSelectedRow();
    
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Debes seleccionar una factura de la tabla");
        return;
    }
    
    int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Estás seguro de eliminar esta factura?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );
    
    if (confirmacion == JOptionPane.YES_OPTION) {
        int id = Integer.parseInt(tablafacturas.getValueAt(fila, 0).toString());
        
        if (facturaDAO.eliminar(id)) {
            JOptionPane.showMessageDialog(this, "Factura eliminada correctamente");
            cargarTabla();
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al eliminar la factura");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

