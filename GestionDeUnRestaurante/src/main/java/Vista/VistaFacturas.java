    private void cargarTabla() {
    
    DefaultTableModel modelo = (DefaultTableModel) tablafacturas.getModel();
    modelo.setRowCount(0);

    
    List<Factura> lista = facturaDAO.listar();

    for (Factura factura : lista) {
        modelo.addRow(new Object[]{
            factura.getIDFactura(),      
            factura.getIDPedido(),
            factura.getFecha()!= null ? factura.getFecha().toString() : "",
            factura.getTotal(),
            factura.getMetodoPago(),


        });
    }
    }
     private void limpiarCampos() {
        cmbPedido.setSelectedIndex(-1);  
        jftfFecha.setText("");                 
    txtTotal.setText("");
         cmbMetodoPago.setSelectedIndex(0);  
}
     private void cargarPedidos() {
    cmbPedido.removeAllItems();
    
    PedidoDAO pedidoDAO = new PedidoDAO();
    List<Pedido> lista = pedidoDAO.listar();
    
    for (Pedido pedido : lista) {
        
        cmbPedido.addItem(pedido.getIDPedido() + " - Estado: " + pedido.getEstado());
    }
}
     private void verificarDetalles(int idPedido) {
    DetallePedidoDAO detalleDAO = new DetallePedidoDAO();
    List<DetallePedido> lista = detalleDAO.listarPorPedido(idPedido);
    
    System.out.println("Detalles encontrados para el pedido " + idPedido + ": " + lista.size());
    
    for (DetallePedido d : lista) {
        System.out.println("Plato: " + d.getIDPlato() + " | Cantidad: " + d.getCantidad() + " | Subtotal: " + d.getSubTotal());
    }
}
     

