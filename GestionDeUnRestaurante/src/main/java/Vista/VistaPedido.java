    private void cargarCombos() {
    
    
    cmbMesa.removeAllItems();
    List<Mesa> mesas = mesaDAO.listar();
    for (Mesa mesa : mesas) {
        cmbMesa.addItem(mesa.getIDMesa() + " - Mesa " + mesa.getNumero());
    }
    
    
    cmbCliente.removeAllItems();
    List<Cliente> clientes = clienteDAO.listar();
    for (Cliente cliente : clientes) {
        cmbCliente.addItem(cliente.getIDCliente() + " - " + cliente.getNombre());
    }
    
    
    cmbPlatos.removeAllItems();
    List<Plato> platos = platoDAO.listar();
    for (Plato plato : platos) {
        cmbPlatos.addItem(plato.getIDPlato() + " - " + plato.getNombre() + " ($" + plato.getPrecio() + ")");
    }
    
    
    cmbEstado.removeAllItems();
    cmbEstado.addItem("Pendiente");
    cmbEstado.addItem("Servido");
    cmbEstado.addItem("Pagado");
}
    private void limpiarDetalle() {
    cmbPlatos.setSelectedIndex(-1);
    txtCantidad.setText("");
}

