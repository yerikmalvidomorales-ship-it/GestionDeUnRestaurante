    private void btnGuardarPedidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarPedidoActionPerformed
if (cmbMesa.getSelectedIndex() == -1) {
        JOptionPane.showMessageDialog(this, "Debes seleccionar una mesa");
        return;
    }
    
    if (cmbCliente.getSelectedIndex() == -1) {
        JOptionPane.showMessageDialog(this, "Debes seleccionar un cliente");
        return;
    }
    
    DefaultTableModel modelo = (DefaultTableModel) tabladetalles.getModel();
    
    if (modelo.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Debes agregar al menos un plato");
        return;
    }
    
    try {
        // ===== 1. Guardar cabecera =====
        Pedido pedido = new Pedido();
        
        String itemMesa = cmbMesa.getSelectedItem().toString();
        int idMesa = Integer.parseInt(itemMesa.split(" - ")[0]);
        
        String itemCliente = cmbCliente.getSelectedItem().toString();
        int idCliente = Integer.parseInt(itemCliente.split(" - ")[0]);
        
        pedido.setIDMesa(idMesa);
        pedido.setIDCliente(idCliente);
        pedido.setFecha(LocalDateTime.now());
        pedido.setEstado(cmbEstado.getSelectedItem().toString());
        
        int idPedidoGenerado = pedidoDAO.agregar(pedido);
        
        if (idPedidoGenerado == -1) {
            JOptionPane.showMessageDialog(this, "Error al guardar el pedido");
            return;
        }
        
        // ===== 2. Guardar detalles =====
        for (int i = 0; i < modelo.getRowCount(); i++) {
            
            Object valor = modelo.getValueAt(i, 0);
            if (valor == null || valor.toString().trim().isEmpty()) {
                continue;
            }
            
            // Columna 0 tiene "1 - Suchi"
            String platoTexto = modelo.getValueAt(i, 0).toString();
            int idPlato = Integer.parseInt(platoTexto.split(" - ")[0]);
            
            int cantidad = Integer.parseInt(modelo.getValueAt(i, 1).toString());
            double subtotal = Double.parseDouble(modelo.getValueAt(i, 2).toString());
            
            DetallePedido detalle = new DetallePedido();
            detalle.setIDPedido(idPedidoGenerado);
            detalle.setIDPlato(idPlato);
            detalle.setCantidad(cantidad);
            detalle.setSubTotal(subtotal);
            
            detalleDAO.agregar(detalle);
        }
        
        JOptionPane.showMessageDialog(this, "Pedido guardado correctamente. ID: " + idPedidoGenerado);
        btnLimpiarActionPerformed(null);
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al guardar el pedido: " + e.getMessage());
        e.printStackTrace();
    }       
    }//GEN-LAST:event_btnGuardarPedidoActionPerformed

