private double calcularTotal() {
    DefaultTableModel modelo = (DefaultTableModel) tabladetalles.getModel();
    double total = 0;
    
    for (int i = 0; i < modelo.getRowCount(); i++) {
        total += Double.parseDouble(modelo.getValueAt(i, 3).toString());
    }
    
    return total;
}
