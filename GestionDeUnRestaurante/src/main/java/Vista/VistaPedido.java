    private void btnAgregarPlatoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarPlatoActionPerformed
       
        
        if (cmbPlatos.getSelectedIndex() == -1) {
        JOptionPane.showMessageDialog(this, "Debes seleccionar un plato");
        return;
    }
    
    if (txtCantidad.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Debes ingresar la cantidad");
        return;
    }
    
    try {
        int cantidad = Integer.parseInt(txtCantidad.getText().trim());
        
        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0");
            return;
        }
        
        // Formato del combo: "1 - Suchi ($30000.0)"
        String itemPlato = cmbPlatos.getSelectedItem().toString();
        String[] partes = itemPlato.split(" - ");
        int idPlato = Integer.parseInt(partes[0]);
        
        String nombrePlato = partes[1].split(" \\(")[0]; // "Suchi"
        
        // Buscar el precio
        double precio = 0;
        List<Plato> platos = platoDAO.listar();
        for (Plato p : platos) {
            if (p.getIDPlato() == idPlato) {
                precio = p.getPrecio();
                break;
            }
        }
        
        double subtotal = cantidad * precio;
        
        // Agregar a la tabla (3 columnas: Plato, Cantidad, SubTotal)
        DefaultTableModel modelo = (DefaultTableModel) tabladetalles.getModel();
        modelo.addRow(new Object[]{
            idPlato + " - " + nombrePlato,  // Columna 0: Plato (guardamos ID + nombre)
            cantidad,                       // Columna 1: Cantidad
            subtotal                        // Columna 2: SubTotal
        });
        
        limpiarDetalle();
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La cantidad debe ser un número válido");
    }
    }//GEN-LAST:event_btnAgregarPlatoActionPerformed

