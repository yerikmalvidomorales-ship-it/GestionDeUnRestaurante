    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        if (txtNumeroMesa.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Debes ingresar el número de mesa");
        return;
    }
    
    try {
        Mesa mesa = new Mesa();
        mesa.setNumero(Integer.parseInt(txtNumeroMesa.getText().trim()));
        mesa.setEstadoMESA(cmbEstado.getSelectedItem().toString());
        
        if (mesaDAO.agregar(mesa)) {
            JOptionPane.showMessageDialog(this, "Mesa agregada correctamente");
            cargarTabla();   
            limpiarCampos(); 
        } else {
            JOptionPane.showMessageDialog(this, "Error al agregar la mesa");
        }
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El número de mesa debe ser un número válido");
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

