    private void tablamesasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablamesasMouseClicked
        int fila = tablamesas.getSelectedRow();
    
    if (fila >= 0) {
        
        txtNumeroMesa.setText(tablamesas.getValueAt(fila, 1).toString());
        cmbEstado.setSelectedItem(tablamesas.getValueAt(fila, 2).toString());
    }
    }//GEN-LAST:event_tablamesasMouseClicked

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        int fila = tablamesas.getSelectedRow();
    
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Debes seleccionar una mesa de la tabla");
        return;
    }
    
    if (txtNumeroMesa.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "El número de mesa no puede estar vacío");
        return;
    }
    
    try {
        Mesa mesa = new Mesa();
        
     
        int id = Integer.parseInt(tablamesas.getValueAt(fila, 0).toString());
        mesa.setIDMesa(id);   
        
        mesa.setNumero(Integer.parseInt(txtNumeroMesa.getText().trim()));
        mesa.setEstadoMESA(cmbEstado.getSelectedItem().toString());
        
        if (mesaDAO.modificar(mesa)) {
            JOptionPane.showMessageDialog(this, "Mesa modificada correctamente");
            cargarTabla();
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al modificar la mesa");
        }
        
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El número de mesa debe ser válido");
    }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tablamesas.getSelectedRow();
    
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Debes seleccionar una mesa de la tabla");
        return;
    }
    
    int confirmacion = JOptionPane.showConfirmDialog(
            this, 
            "¿Estás seguro de eliminar esta mesa?", 
            "Confirmar eliminación", 
            JOptionPane.YES_NO_OPTION
    );
    
    if (confirmacion == JOptionPane.YES_OPTION) {
        int id = Integer.parseInt(tablamesas.getValueAt(fila, 0).toString());
        
        if (mesaDAO.eliminar(id)) {
            JOptionPane.showMessageDialog(this, "Mesa eliminada correctamente");
            cargarTabla();
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "Error al eliminar la mesa");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

